const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const os = require('os');
const root = process.cwd();

// Only the packages that end up inside the app: the ones in the release
// JavaScript bundle, read from its source map. npm's dependency list also
// holds build tools (Babel, Metro, the CLI) that never ship.
function bundledPackages() {
  let mapFile = process.env.NOTICES_MAP;
  if (!mapFile) {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'notices-'));
    mapFile = path.join(dir, 'main.map');
    execSync(
      `npx react-native bundle --platform ios --dev false --entry-file index.js --bundle-output ${path.join(
        dir,
        'main.js',
      )} --sourcemap-output ${mapFile}`,
      { stdio: 'ignore' },
    );
  }
  const map = JSON.parse(fs.readFileSync(mapFile, 'utf8'));
  const sources = [];
  const walk = m =>
    m.sections
      ? m.sections.forEach(x => walk(x.map))
      : sources.push(...(m.sources || []));
  walk(map);
  const names = new Set();
  for (const src of sources) {
    const i = src.lastIndexOf('node_modules/');
    if (i < 0) continue;
    const parts = src.slice(i + 13).split('/');
    names.add(parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0]);
  }
  return names;
}
const inApp = bundledPackages();

// Libraries React Native ships prebuilt inside ReactNativeDependencies;
// CocoaPods does not list them. Texts in scripts/notices-native/, taken
// from each project's release tag.
const NATIVE_EXTRA = [
  ['boost', '1.84.0', 'BSL-1.0'],
  ['double-conversion', '1.1.6', 'BSD-3-Clause'],
  ['fast_float', '8.0.0', 'MIT'],
  ['fmt', '12.1.0', 'MIT'],
  ['folly', '2024.11.18.00', 'Apache-2.0'],
  ['glog', '0.3.5', 'BSD-3-Clause'],
  ['SocketRocket', '0.7.1', 'BSD-3-Clause'],
].map(([name, version, license]) => ({
  name,
  version,
  license,
  text: fs
    .readFileSync(
      path.join(root, 'scripts/notices-native', `${name}.txt`),
      'utf8',
    )
    .trim(),
}));
const out = execSync(
  'npm ls --omit=dev --all --parseable 2>/dev/null || true',
  {
    encoding: 'utf8',
  },
)
  .split('\n')
  .filter(p => p.includes('node_modules'));
const seen = new Map();
for (const dir of out) {
  let pkg;
  try {
    pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  } catch {
    continue;
  }
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) continue;
  const lic = fs
    .readdirSync(dir)
    .find(f => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  seen.set(key, {
    name: pkg.name,
    version: pkg.version,
    license:
      typeof pkg.license === 'string'
        ? pkg.license
        : JSON.stringify(pkg.license ?? 'UNKNOWN'),
    text: lic ? fs.readFileSync(path.join(dir, lic), 'utf8').trim() : null,
  });
}
const list = [...seen.values()]
  .filter(p => inApp.has(p.name))
  .sort((a, b) => a.name.localeCompare(b.name));
// Parts of React Native published without their own licence file are
// covered by React Native's own (MIT, Meta).
const rn = list.find(p => p.name === 'react-native');
for (const p of list) {
  if (p.text == null && p.name.startsWith('@react-native/') && rn) {
    p.text = rn.text;
  }
}
// Packages shipped without a licence file: the standard text of the
// licence they declare, with the copyright line from their source.
const STANDARD = {
  'qrcode-generator': ['MIT', 'Copyright (c) 2009 Kazuhiko Arase'],
  biggystring: ['ISC', 'Copyright (c) Airbitz, Inc.'],
};
for (const p of list) {
  const std = STANDARD[p.name];
  if (p.text == null && std) {
    const body = fs.readFileSync(
      path.join(root, 'scripts/notices-native', `${std[0]}.txt`),
      'utf8',
    );
    p.text = `${std[1]}\n\n${body.trim()}`;
  }
  if (p.text == null && p.name === 'metro-runtime' && rn) p.text = rn.text;
}
const missing = [...inApp].filter(n => !list.some(p => p.name === n));
if (missing.length > 0) {
  throw new Error(`In the app but not found by npm: ${missing.join(', ')}`);
}
let md = `# Third-party notices\n\nZecky Lock it includes the open-source software listed below. Generated by\n\`scripts/notices.js\` from the installed packages (audit C-54); regenerate\nafter any dependency change.\n\n## Zcash engine\n\nThe Zecky engine (zecky-app/zecky-engine) is built from the official Zcash\ncore, librustzcash, and its dependencies, published under MIT OR Apache-2.0;\nthe engine itself is MIT (see its LICENSE). The engine repository lists its\ncrates in Cargo.lock.\n\n## JavaScript packages (${list.length})\n\n`;
for (const p of list) {
  md += `### ${p.name} ${p.version}\n\nLicense: ${p.license}\n\n`;
  md += p.text
    ? '```\n' + p.text + '\n```\n\n'
    : '_No license file in the package; see its license field above._\n\n';
}
const ack = path.join(
  root,
  'ios/Pods/Target Support Files/Pods-Zecky/Pods-Zecky-acknowledgements.markdown',
);
if (fs.existsSync(ack)) {
  md +=
    '## iOS libraries (CocoaPods)\n\n' +
    fs.readFileSync(ack, 'utf8').replace(/^# /gm, '### ').trim() +
    '\n\n';
}
md += '## Inside React Native (prebuilt)\n\n';
for (const p of NATIVE_EXTRA) {
  md += `### ${p.name} ${p.version}\n\nLicense: ${p.license}\n\n\`\`\`\n${p.text}\n\`\`\`\n\n`;
}
md +=
  '## Fonts\n\nInter and Newsreader, SIL Open Font License 1.1 (https://openfontlicense.org).\n';
fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), md);

// The same notices for the app's Acknowledgements page (Settings › About),
// with each licence text stored once.
const texts = [];
const textIndex = new Map();
const ref = text => {
  if (text == null) return -1;
  const t = text.trim();
  if (!textIndex.has(t)) {
    textIndex.set(t, texts.length);
    texts.push(t);
  }
  return textIndex.get(t);
};
const sections = [
  {
    title: 'Zcash engine',
    note: 'Built from the official Zcash core, librustzcash, and its dependencies, published under MIT OR Apache-2.0. The Zecky engine itself is MIT. Its Cargo.lock lists every crate.',
    items: [],
  },
  {
    title: 'JavaScript packages',
    items: list.map(p => ({
      n: p.name,
      v: p.version,
      l: p.license,
      t: ref(p.text),
    })),
  },
];
if (fs.existsSync(ack)) {
  const lock = fs.readFileSync(path.join(root, 'ios/Podfile.lock'), 'utf8');
  const pods = new Map();
  for (const m of lock.matchAll(/^ {2}- ([^\s/(]+)(?:\/\S+)? \(([^)]+)\)/gm)) {
    if (!pods.has(m[1])) pods.set(m[1], m[2]);
  }
  const items = [];
  let cur = null;
  for (const line of fs.readFileSync(ack, 'utf8').split('\n')) {
    const h = line.match(/^## (\S+)$/);
    if (h && pods.has(h[1])) {
      cur = { n: h[1], v: pods.get(h[1]), lines: [] };
      items.push(cur);
    } else if (cur) cur.lines.push(line);
  }
  const last = items[items.length - 1];
  if (last) {
    const end = last.lines.findIndex(l => /^Generated by CocoaPods/.test(l));
    if (end >= 0) last.lines = last.lines.slice(0, end);
  }
  sections.push({
    title: 'iOS libraries',
    items: [
      ...items.map(i => ({
        n: i.n,
        v: i.v,
        l: '',
        t: ref(i.lines.join('\n')),
      })),
      ...NATIVE_EXTRA.map(p => ({
        n: p.name,
        v: p.version,
        l: p.license,
        t: ref(p.text),
      })),
    ].sort((a, b) => a.n.localeCompare(b.n, 'en', { sensitivity: 'base' })),
  });
}
sections.push({
  title: 'Fonts',
  note: 'Inter and Newsreader, SIL Open Font License 1.1.',
  items: [],
});
fs.writeFileSync(
  path.join(root, 'src/lib/notices.json'),
  JSON.stringify({ sections, texts }),
);
// A build script, not app code: it reports on stdout, without console.
process.stdout.write(
  `${list.length} packages; ${
    fs.existsSync(ack) ? 'pods included' : 'no pods ack'
  }\n`,
);
process.stdout.write(
  `${list
    .filter(p => !p.text)
    .map(p => `${p.name} ${p.license}`)
    .join('\n')}\n`,
);
