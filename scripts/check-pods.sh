#!/usr/bin/env bash
# Audit C-35: CocoaPods checks only the podspecs, not the downloaded code, and
# fetches it from tags that can be moved. This records a SHA-256 for every
# downloaded pod (the Zcash SDK's TLS, gRPC and BIP 39 libraries, and React
# Native's prebuilt binaries) in ios/Pods.sha256 and, at every `pod install`,
# refuses Pods that differ. Local pods (from node_modules) are checked by npm.
#
#   scripts/check-pods.sh          verify (run by the Podfile after install)
#   scripts/check-pods.sh --write  record, after a deliberate pod update
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PODS="$ROOT/ios/Pods"
MANIFEST="$ROOT/ios/Pods.sha256"

if command -v shasum >/dev/null; then
  sum() { shasum -a 256 | cut -d ' ' -f 1; }
else
  sum() { sha256sum | cut -d ' ' -f 1; }
fi

# Generated by CocoaPods itself, not downloaded.
SKIP='^(Headers|Local Podspecs|Target Support Files|Pods\.xcodeproj|Manifest\.lock)$'

# One line per downloaded pod: SHA-256 over the sorted list of its file hashes.
pod_hash() {
  (cd "$1" && find . -type f ! -name '.DS_Store' -print0 | LC_ALL=C sort -z |
    while IFS= read -r -d '' f; do printf '%s  %s\n' "$(sum < "$f")" "$f"; done) | sum
}

current() {
  local name
  for dir in "$PODS"/*/; do
    name="$(basename "$dir")"
    [[ "$name" =~ $SKIP ]] && continue
    printf '%s  %s\n' "$(pod_hash "$dir")" "$name"
  done | LC_ALL=C sort -k 2
}

if [[ "${1:-}" == "--write" ]]; then
  current > "$MANIFEST"
  echo "check-pods: recorded $(wc -l < "$MANIFEST" | tr -d ' ') pods in ios/Pods.sha256."
  exit 0
fi

if [[ ! -f "$MANIFEST" ]]; then
  echo "check-pods: ios/Pods.sha256 is missing. Refused." >&2
  exit 1
fi
if ! diff <(current) "$MANIFEST" >/tmp/check-pods.diff; then
  echo "check-pods: the downloaded Pods differ from ios/Pods.sha256. Refused." >&2
  cat /tmp/check-pods.diff >&2
  echo "If this was a deliberate pod update, review it and run scripts/check-pods.sh --write." >&2
  exit 1
fi
echo "check-pods: all $(wc -l < "$MANIFEST" | tr -d ' ') downloaded pods match."
